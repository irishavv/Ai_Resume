import { jsPDF } from 'jspdf';
import { formatDate, scoreBand } from './format.js';

const PAGE_WIDTH = 210;
const PAGE_HEIGHT = 297;
const MARGIN = 16;
const CONTENT_WIDTH = PAGE_WIDTH - MARGIN * 2;
const CONTENT_BOTTOM = PAGE_HEIGHT - MARGIN;

const INK = [17, 24, 39];
const MUTED = [71, 85, 105];
const SUBTLE = [100, 116, 139];
const ACCENT = [37, 99, 235];

/** Starts a new document and draws the shared report header. */
function createDocument(title, candidateName) {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(...INK);
  doc.text(String(candidateName || 'Candidate'), MARGIN, MARGIN + 4);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(...SUBTLE);
  doc.text(String(title), MARGIN, MARGIN + 10);
  doc.text(`Generated ${formatDate(new Date())}`, PAGE_WIDTH - MARGIN, MARGIN + 10, { align: 'right' });

  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(0.3);
  doc.line(MARGIN, MARGIN + 14, PAGE_WIDTH - MARGIN, MARGIN + 14);

  return { doc, y: MARGIN + 21 };
}

/** Adds a page when the requested height would overflow the current one. */
function ensureSpace(doc, y, needed) {
  if (y + needed <= CONTENT_BOTTOM) return y;
  doc.addPage();
  return MARGIN;
}

/**
 * Writes wrapped text and returns the next vertical position.
 * `size` is in points, matching the PDF typographic scale.
 */
function writeText(
  doc,
  y,
  text,
  { size = 10, style = 'normal', color = INK, gap = 2.5, indent = 0 } = {},
) {
  const content = String(text ?? '');
  if (!content.trim()) return y;

  doc.setFont('helvetica', style);
  doc.setFontSize(size);
  doc.setTextColor(...color);

  const width = CONTENT_WIDTH - indent;
  const lines = doc.splitTextToSize(content, width);
  const lineHeight = size * 0.5;

  let cursor = y;
  for (const line of lines) {
    cursor = ensureSpace(doc, cursor, lineHeight);
    doc.text(line, MARGIN + indent, cursor);
    cursor += lineHeight;
  }

  return cursor + gap;
}

function writeHeading(doc, y, text) {
  const cursor = ensureSpace(doc, y, 7);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(...SUBTLE);
  const label = String(text).toUpperCase();
  doc.text(label, MARGIN, cursor);
  return cursor + 5;
}

function writeBullet(doc, y, text) {
  const cursor = ensureSpace(doc, y, 5);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(...ACCENT);
  doc.text('•', MARGIN + 1, cursor);
  return writeText(doc, cursor, text, { indent: 5, gap: 1.5 });
}

function toItems(value) {
  return Array.isArray(value) ? value.map((item) => String(item).trim()).filter(Boolean) : [];
}

/**
 * Converts the markdown the assistant answers with into readable plain text.
 * Only the inline constructs that would otherwise look like noise are removed.
 */
export function stripMarkdown(value) {
  return String(value ?? '')
    .replace(/```[a-zA-Z0-9]*\n?/g, '')
    .replace(/`([^`]+)`/g, '$1')
    .replace(/!\[[^\]]*\]\(([^)]+)\)/g, '$1')
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '$1 ($2)')
    .replace(/^\s{0,3}#{1,6}\s+/gm, '')
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    .replace(/__([^_]+)__/g, '$1')
    .replace(/(^|\W)\*([^*\n]+)\*(?=\W|$)/g, '$1$2')
    .replace(/(^|\W)_([^_\n]+)_(?=\W|$)/g, '$1$2')
    .replace(/^\s*>\s?/gm, '')
    .trim();
}

function fileName(prefix, candidateName) {
  const slug = String(candidateName || 'candidate')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 40);
  const stamp = new Date().toISOString().slice(0, 10);
  return `${prefix}-${slug || 'candidate'}-${stamp}.pdf`;
}

/**
 * Exports a conversation transcript as a PDF.
 *
 * @param {{ candidateName?: string, title?: string, messages?: Array<{role:string,content:string}> }} input
 */
export function exportConversationPdf({ candidateName, title, messages = [] } = {}) {
  const { doc, y: start } = createDocument(title || 'Conversation transcript', candidateName);
  let y = start;

  const usable = messages.filter((message) => message && String(message.content || '').trim());
  if (usable.length === 0) {
    writeText(doc, y, 'This conversation has no messages yet.', { color: SUBTLE });
  }

  usable.forEach((message) => {
    const isUser = message.role === 'user';
    y = writeHeading(doc, y, isUser ? 'Recruiter' : 'Assistant');
    y = writeText(doc, y, stripMarkdown(message.content), { gap: 4 });
  });

  doc.setFont('helvetica', 'italic');
  doc.setFontSize(8);
  doc.setTextColor(...SUBTLE);
  const footer = ensureSpace(doc, y, 6);
  doc.text(
    'Generated by the AI Portfolio assistant from the verified candidate profile.',
    MARGIN,
    footer,
  );

  doc.save(fileName('conversation', candidateName));
}

/**
 * Exports a job-match report as a PDF.
 *
 * @param {{ candidateName?: string, result?: object }} input
 */
export function exportJobMatchPdf({ candidateName, result } = {}) {
  if (!result) return;

  const { doc, y: start } = createDocument('Job match report', candidateName);
  let y = start;

  const band = scoreBand(result.suitabilityScore);
  y = writeText(
    doc,
    y,
    `Suitability: ${Number(result.suitabilityScore) || 0}/100 — ${result.scoreLabel || band.label}`,
    { size: 13, style: 'bold', color: INK, gap: 3 },
  );

  if (result.summary) {
    y = writeText(doc, y, stripMarkdown(result.summary), { color: MUTED, gap: 4 });
  }

  const rubric = Array.isArray(result.rubric) ? result.rubric : [];
  if (rubric.length > 0) {
    y = writeHeading(doc, y, 'Scoring rubric');
    rubric.forEach((item) => {
      const weight = item.weight == null ? '' : ` (weight ${item.weight}%)`;
      const awarded = item.awardedScore == null ? '' : ` — awarded ${item.awardedScore}`;
      y = writeText(doc, y, `${item.criterion || 'Criterion'}${weight}${awarded}`, {
        style: 'bold',
        color: INK,
        gap: 1,
      });
      if (item.rationale) {
        y = writeText(doc, y, stripMarkdown(item.rationale), { color: MUTED, indent: 4, gap: 2.5 });
      }
    });
    y += 1;
  }

  const requirements = Array.isArray(result.matchedRequirements)
    ? result.matchedRequirements.filter((item) => item && item.requirement)
    : [];
  if (requirements.length > 0) {
    y = writeHeading(doc, y, 'Requirements');
    requirements.forEach((item) => {
      const status = item.matched ? 'Matched' : 'Not evidenced';
      y = writeText(doc, y, `[${status}] ${item.requirement}`, { color: INK, gap: 1 });
      if (item.evidence) {
        y = writeText(doc, y, `Evidence: ${stripMarkdown(item.evidence)}`, {
          color: MUTED,
          indent: 4,
          gap: 2.5,
        });
      }
    });
    y += 1;
  }

  const sections = [
    ['Missing or unverified', toItems(result.missingOrUnverified)],
    ['Strengths', toItems(result.strengths)],
    ['Areas to evaluate', toItems(result.areasToEvaluate)],
    ['Suggested interview questions', toItems(result.suggestedInterviewQuestions)],
    ['Limitations', toItems(result.limitations)],
  ];

  sections.forEach(([heading, items]) => {
    if (items.length === 0) return;
    y = writeHeading(doc, y, heading);
    items.forEach((item) => {
      y = writeBullet(doc, y, stripMarkdown(item));
    });
    y += 1;
  });

  if (result.disclaimer) {
    y = writeHeading(doc, y, 'Disclaimer');
    y = writeText(doc, y, stripMarkdown(result.disclaimer), { size: 9, color: MUTED });
  }

  doc.save(fileName('job-match', candidateName));
}
